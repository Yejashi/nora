#!/usr/bin/env bash
# N30: install nora for the current user.
#
# Installs:
#   binary        -> ~/.local/bin/nora (on NixOS: a wrapper there and the
#                    binary under ~/.local/libexec/nora/)
#   terminfo      -> ~/.terminfo (compiled from terminfo/nora.terminfo)
#   desktop entry -> ~/.local/share/applications/nora.desktop
#   icon          -> ~/.local/share/icons/hicolor/128x128/apps/nora.png
#
# User config is preserved: an existing ~/.config/nora/config.toml is
# never touched. When no config exists, the example config is copied in
# as a starting point.
set -euo pipefail

cd "$(dirname "$0")/.."

PREFIX="${HOME}/.local"
BIN_DIR="$PREFIX/bin"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/nora"

# Always build: cargo is incremental (a current build costs a second),
# and `git pull && ./scripts/install.sh` must not install a stale binary.
echo "==> building nora (release)"
cargo build --release
# Where cargo put it: CARGO_TARGET_DIR (absolute, or relative to the repo
# root, which is the current directory) or the default `target`.
BUILT="${CARGO_TARGET_DIR:-target}/release/nora"

echo "==> installing binary to $BIN_DIR"
mkdir -p "$BIN_DIR"
if [ -f /etc/NIXOS ] && command -v nix >/dev/null 2>&1; then
    # NixOS has no global library path. nora loads libvulkan, libwayland,
    # libxkbcommon and the X11 client libraries at runtime, so install the
    # binary under libexec behind a wrapper that supplies those directories
    # from the nixpkgs store. `nix build` only fetches cached outputs.
    echo "    NixOS detected: resolving runtime libraries from nixpkgs"
    LIBEXEC_DIR="$PREFIX/libexec/nora"
    LIB_OUTS=$(nix build --extra-experimental-features 'nix-command flakes' \
        --no-link --print-out-paths \
        nixpkgs#vulkan-loader nixpkgs#wayland nixpkgs#libxkbcommon \
        nixpkgs#xorg.libX11 nixpkgs#xorg.libXcursor nixpkgs#xorg.libXi \
        nixpkgs#xorg.libXrandr nixpkgs#xorg.libxcb)
    # Keep only the outputs that actually carry shared objects (nix prints
    # every output, including -dev and -man).
    LIB_DIRS=$(for out in $LIB_OUTS; do
        if ls "$out"/lib/*.so* >/dev/null 2>&1; then printf '%s/lib\n' "$out"; fi
    done | paste -sd:)
    mkdir -p "$LIBEXEC_DIR"
    install -m 0755 "$BUILT" "$LIBEXEC_DIR/nora"
    cat > "$BIN_DIR/nora" <<EOF_WRAPPER
#!/bin/sh
# nora launcher (NixOS): generated by scripts/install.sh.
export LD_LIBRARY_PATH="$LIB_DIRS\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec "$LIBEXEC_DIR/nora" "\$@"
EOF_WRAPPER
    chmod 0755 "$BIN_DIR/nora"
else
    install -m 0755 "$BUILT" "$BIN_DIR/nora"
fi
"$BIN_DIR/nora" --version

echo "==> installing terminfo to ~/.terminfo"
if command -v tic >/dev/null 2>&1; then
    # Compile the entry into the per-user terminfo database.
    tic -x -o "$HOME/.terminfo" terminfo/nora.terminfo
else
    # ncurses reads only compiled entries; a copied source file would be
    # an unreadable entry. Without one, nora sets TERM=xterm-256color.
    echo "    skipped: 'tic' (ncurses) is needed to compile the terminfo entry;"
    echo "    until it is installed, nora uses TERM=xterm-256color"
fi

echo "==> installing desktop entry to $PREFIX/share/applications"
mkdir -p "$PREFIX/share/applications"
install -m 0644 resources/nora.desktop "$PREFIX/share/applications/nora.desktop"
update-desktop-database "$PREFIX/share/applications" 2>/dev/null || true

echo "==> installing icon to $PREFIX/share/icons"
ICON_DIR="$PREFIX/share/icons/hicolor/128x128/apps"
mkdir -p "$ICON_DIR"
install -m 0644 resources/nora.png "$ICON_DIR/nora.png"

echo "==> preserving user config"
CONFIG_FILE="$CONFIG_DIR/config.toml"
if [ -f "$CONFIG_FILE" ]; then
    echo "    existing config preserved: $CONFIG_FILE"
else
    mkdir -p "$CONFIG_DIR"
    install -m 0644 resources/nora.example.toml "$CONFIG_FILE"
    echo "    installed example config: $CONFIG_FILE"
fi

echo "install complete: $BIN_DIR/nora"
